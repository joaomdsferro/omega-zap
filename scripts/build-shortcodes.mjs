// Regenerates src/data/shortcodes.ts: the ":name:" shortcodes Slack and
// GitHub use (":laughing:" for 😆, ":+1:" for 👍), from emoji-datasource.
//   node scripts/build-shortcodes.mjs
import { readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile(new URL("../node_modules/emoji-datasource-apple/emoji.json", import.meta.url), "utf8"));
const toEmoji = (unified) => String.fromCodePoint(...unified.split("-").map((hex) => parseInt(hex, 16)));

const codes = {};
for (const entry of data.sort((a, b) => a.sort_order - b.sort_order)) {
  for (const name of entry.short_names) codes[name] ??= toEmoji(entry.unified);
}

const body = `// Generated by scripts/build-shortcodes.mjs from emoji-datasource. Do not edit by hand.

/** Each ":name:" shortcode and its emoji. */
export const SHORTCODES: Record<string, string> = ${JSON.stringify(codes, null, 1)};
`;
await writeFile(new URL("../src/data/shortcodes.ts", import.meta.url), body);
console.log(`${Object.keys(codes).length} shortcodes`);
