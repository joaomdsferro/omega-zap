// Regenerates src/data/emoji.ts from the Unicode emoji list:
//   node scripts/build-emoji.mjs [emoji version] [CLDR release]
// The search keywords ("like" for 👍) come from the matching CLDR release.
import { writeFile } from "node:fs/promises";

const version = process.argv[2] ?? "17.0";
const cldr = process.argv[3] ?? "48";
const source = `https://unicode.org/Public/${version}.0/emoji/emoji-test.txt`;
const annotations = ["annotations", "annotationsDerived"].map(
  (dir) => `https://raw.githubusercontent.com/unicode-org/cldr/release-${cldr}/common/${dir}/en.xml`,
);

async function text(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response.text();
}

// CLDR keys its keywords by the emoji without variation selectors.
const bare = (emoji) => emoji.replaceAll("\uFE0F", "");
const unescape = (xml) => xml.replaceAll("&amp;", "&").replaceAll("&lt;", "<").replaceAll("&gt;", ">");

const keywords = new Map();
for (const url of annotations) {
  for (const [, cp, list] of (await text(url)).matchAll(/<annotation cp="([^"]+)">([^<]*)<\/annotation>/g)) {
    keywords.set(bare(cp), unescape(list).toLowerCase().split(" | "));
  }
}

// The picker's sections, in the order the phone apps show them.
const SECTIONS = [
  { name: "Smileys & People", icon: "😀", groups: ["Smileys & Emotion", "People & Body"] },
  { name: "Animals & Nature", icon: "🐻", groups: ["Animals & Nature"] },
  { name: "Food & Drink", icon: "🍔", groups: ["Food & Drink"] },
  { name: "Activity", icon: "⚽", groups: ["Activities"] },
  { name: "Travel & Places", icon: "🚗", groups: ["Travel & Places"] },
  { name: "Objects", icon: "💡", groups: ["Objects"] },
  { name: "Symbols", icon: "🔣", groups: ["Symbols"] },
  { name: "Flags", icon: "🏳️", groups: ["Flags"] },
];

const byGroup = new Map();
let group = "";
for (const line of (await text(source)).split("\n")) {
  if (line.startsWith("# group:")) group = line.slice(8).trim();
  const match = /^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.+)$/.exec(line);
  // Skin tone variants would bury every hand and person under five copies.
  if (!match || match[2].includes("skin tone")) continue;
  if (!byGroup.has(group)) byGroup.set(group, []);
  const [, emoji, name] = match;
  // Only what the name does not already say.
  const extra = (keywords.get(bare(emoji)) ?? []).filter((keyword) => !name.toLowerCase().includes(keyword));
  byGroup.get(group).push(extra.length ? `${emoji} ${name}\t${extra.join(" ")}` : `${emoji} ${name}`);
}

const sections = SECTIONS.map(({ name, icon, groups }) => ({
  name,
  icon,
  emoji: groups.flatMap((g) => byGroup.get(g) ?? []),
}));
const total = sections.reduce((sum, section) => sum + section.emoji.length, 0);

const body = `// Generated by scripts/build-emoji.mjs from Unicode Emoji ${version} and CLDR ${cldr}. Do not edit by hand.

export interface EmojiSection {
  name: string;
  /** The emoji on the section's tab. */
  icon: string;
  /** Each entry is the emoji, a space, its name and, after a tab, more words to find it by. */
  emoji: string[];
}

export const EMOJI_VERSION = ${JSON.stringify(version)};

export const EMOJI_SECTIONS: EmojiSection[] = ${JSON.stringify(sections, null, 1)};
`;
await writeFile(new URL("../src/data/emoji.ts", import.meta.url), body);
console.log(`Emoji ${version}: ${total} emoji in ${sections.length} sections`);
