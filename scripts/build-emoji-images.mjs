// Regenerates src/data/emoji-images.ts from emoji-datasource-apple:
//   node scripts/build-emoji-images.mjs
// WhatsApp Web and Signal Desktop both draw Apple's emoji, so we do too. The
// images themselves are served from node_modules by the vite config.
import { readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile("node_modules/emoji-datasource-apple/emoji.json", "utf8"));
const version = JSON.parse(await readFile("node_modules/emoji-datasource-apple/package.json", "utf8")).version;

const toEmoji = (unified) => String.fromCodePoint(...unified.split("-").map((hex) => parseInt(hex, 16)));
// Text writes the same emoji with and without variation selectors; the key leaves them out.
const bare = (emoji) => emoji.replaceAll("️", "");

const entries = [];
for (const entry of data) {
  const variants = [entry, ...Object.values(entry.skin_variations ?? {})];
  for (const variant of variants) {
    if (!variant.has_img_apple) continue;
    entries.push([bare(toEmoji(variant.unified)), variant.image.replace(/\.png$/, "")]);
  }
}

// The file name is the code points in hex, so only the exceptions need storing.
const stemOf = (key) => [...key].map((c) => c.codePointAt(0).toString(16)).join("-");
const plain = entries.filter(([key, stem]) => stemOf(key) === stem).map(([key]) => key);
const odd = Object.fromEntries(entries.filter(([key, stem]) => stemOf(key) !== stem));

await writeFile(
  "src/data/emoji-images.ts",
  `// Generated by scripts/build-emoji-images.mjs from emoji-datasource-apple ${version}. Do not edit by hand.

/** Emoji with an Apple image named after their code points, variation selectors left out. */
export const PLAIN = new Set<string>(${JSON.stringify(plain)});

/** Emoji whose image keeps a variation selector in its name. */
export const ODD: Record<string, string> = ${JSON.stringify(odd)};
`,
);
console.log(`${entries.length} emoji, ${Object.keys(odd).length} with odd names`);
